// Builds apps-script/Code.gs: the shared export logic (js/gantt-export.js)
// followed by the Apps Script wrapper (apps-script/sync.gs). Run after
// changing either file:  node tools/build-apps-script.mjs
// With --check it only verifies Code.gs is up to date.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const out = '// Personal Gantt calendar sync for Google Apps Script.\n'
  + '// Generated by tools/build-apps-script.mjs from js/gantt-export.js and apps-script/sync.gs; edit those, not this.\n\n'
  + read('js/gantt-export.js') + '\n' + read('apps-script/sync.gs');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = read('apps-script/Code.gs'); } catch {}
  if (cur !== out) { console.error('apps-script/Code.gs is out of date: run node tools/build-apps-script.mjs'); process.exit(1); }
  console.log('apps-script/Code.gs is up to date');
} else {
  writeFileSync(new URL('apps-script/Code.gs', root), out);
  console.log('wrote apps-script/Code.gs');
}
